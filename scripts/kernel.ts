/**
 * `npm run kernel`: compiles src/rank/kernel.wat into src/rank/kernel-wasm.ts (the module's bytes
 * as base64), so the client needs no build step for WebAssembly. A unit test runs `compileKernel`
 * and checks the committed file matches.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import wabtInit from 'wabt';

const WAT = new URL('../src/rank/kernel.wat', import.meta.url);
export const KERNEL_TS = new URL('../src/rank/kernel-wasm.ts', import.meta.url);

/** The generated TypeScript module for the current kernel.wat. */
export async function compileKernel(): Promise<string> {
  const wabt = await wabtInit();
  const module = wabt.parseWat('kernel.wat', await readFile(WAT, 'utf8'), { simd: true });
  module.validate();
  const { buffer } = module.toBinary({});
  module.destroy();
  const base64 = Buffer.from(buffer).toString('base64');
  return `// Generated by \`npm run kernel\` from kernel.wat: do not edit.\n\n/** The similarity kernel's WebAssembly module (${buffer.length} bytes), base64. */\nexport const KERNEL_WASM =\n  '${base64}';\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(KERNEL_TS, await compileKernel());
  console.log(`wrote ${fileURLToPath(KERNEL_TS)}`);
}
